-- ============================================================
--  SCENE TIMER: ring the phone even when the app is closed
--
--  When a responder starts (or snoozes) the Scene Timer, the app
--  writes one row here: "ring THIS phone at this time". The push
--  worker checks the table once a minute, waits for the exact
--  second, sends the push, and removes the row. Ending the timer
--  removes the row too.
--
--  One row per phone (endpoint), so a snooze simply moves the time.
--
--  Run once in Supabase: SQL Editor -> New query -> paste -> Run.
-- ============================================================

create table if not exists public.scene_alarms (
  id          bigint generated by default as identity primary key,
  unit        text not null,
  endpoint    text not null unique,     -- which phone (same value as push_subs.endpoint)
  due_at      timestamptz not null,     -- when to ring
  title       text not null default 'Scene Timer',
  body        text not null default '',
  created_at  timestamptz not null default now(),
  sent_at     timestamptz               -- set by the worker the moment it takes the alarm
);

create index if not exists idx_scene_alarms_due on public.scene_alarms (due_at) where sent_at is null;

revoke all on public.scene_alarms from anon;
grant select, insert, update, delete on public.scene_alarms to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.scene_alarms enable row level security;

-- A member manages only their own alarms. The worker uses the service key and is not limited by this.
drop policy if exists "own alarms" on public.scene_alarms;
create policy "own alarms" on public.scene_alarms
  for all to authenticated
  using      ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) )
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) );

