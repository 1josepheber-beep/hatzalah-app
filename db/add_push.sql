-- ============================================================
--  PUSH NOTIFICATIONS
--
--  One row per phone that allowed notifications. The app writes
--  the row when a member taps Allow (and refreshes it on every
--  open); the sender (Cloudflare Worker) reads the rows with the
--  service key and removes phones the push service reports gone.
--
--  Personal messages reuse the announcements table with
--  audience = 'unit:H-24', so they show on that one member's
--  home screen until read. The read rule below keeps other
--  members from seeing them.
--
--  Run once in Supabase: SQL Editor -> New query -> paste -> Run.
-- ============================================================

create table if not exists public.push_subs (
  id          bigint generated by default as identity primary key,
  unit        text not null,
  endpoint    text not null unique,     -- the phone's address at Apple / Google / Mozilla
  p256dh      text not null,            -- the phone's public key (for encrypting to it)
  auth        text not null,            -- the phone's auth secret
  ua          text,                     -- which phone / browser, for the admin's benefit
  created_at  timestamptz not null default now(),
  last_seen   timestamptz not null default now()
);

create index if not exists idx_push_subs_unit on public.push_subs (unit);

revoke all on public.push_subs from anon;
grant select, insert, update, delete on public.push_subs to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.push_subs enable row level security;

-- A member manages their own phones; admins can see everyone's.
drop policy if exists "own or admin read" on public.push_subs;
create policy "own or admin read" on public.push_subs
  for select to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() );

drop policy if exists "own write" on public.push_subs;
create policy "own write" on public.push_subs
  for insert to authenticated
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) );

drop policy if exists "own update" on public.push_subs;
create policy "own update" on public.push_subs
  for update to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) )
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) );

drop policy if exists "own or admin delete" on public.push_subs;
create policy "own or admin delete" on public.push_subs
  for delete to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() );


-- ---------- personal messages: only the addressee (and admins) can read them ----------
drop policy if exists "member read" on public.announcements;
create policy "member read" on public.announcements
  for select to authenticated
  using (
    public.is_member() and (
      lower(coalesce(audience,'everyone')) not like 'unit:%'
      or lower(trim(substring(coalesce(audience,'') from 6))) = lower(trim(coalesce(public.my_unit(),'~none~')))
      or public.is_admin()
    )
  );


-- ---------- the two settings the app reads ----------
-- Fill the values in after the worker is deployed:
--   Push Worker URL  = the worker's address, e.g. https://hoh-push.<your-name>.workers.dev
--   Push Public Key  = the VAPID public key (the same one in the worker's secrets)
insert into public.settings (setting, value)
select 'Push Worker URL', '' where not exists (select 1 from public.settings where setting = 'Push Worker URL');
insert into public.settings (setting, value)
select 'Push Public Key', '' where not exists (select 1 from public.settings where setting = 'Push Public Key');

