-- ---------- 2. each member's bag ----------
create table if not exists public.jumpbag_status (
  id          bigint generated by default as identity primary key,
  unit        text not null,
  item_id     bigint not null references public.jumpbag_items(id) on delete cascade,
  status      text not null default '',     -- have | short | missing | '' (not checked)
  exp_date    date,                         -- when this item expires, if it does
  updated_at  timestamptz not null default now(),
  unique (unit, item_id)
);
create index if not exists idx_jumpbag_status_unit on public.jumpbag_status (unit);
create index if not exists idx_jumpbag_status_exp  on public.jumpbag_status (exp_date) where exp_date is not null;
revoke all on public.jumpbag_status from anon;
grant select, insert, update, delete on public.jumpbag_status to authenticated;
alter table public.jumpbag_status enable row level security;
drop policy if exists "own or admin read" on public.jumpbag_status;
create policy "own or admin read" on public.jumpbag_status for select to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() );
drop policy if exists "own write" on public.jumpbag_status;
create policy "own write" on public.jumpbag_status for insert to authenticated
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) );
drop policy if exists "own update" on public.jumpbag_status;
create policy "own update" on public.jumpbag_status for update to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) )
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) );
drop policy if exists "own or admin delete" on public.jumpbag_status;
create policy "own or admin delete" on public.jumpbag_status for delete to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() );

-- ---------- 3. the reminder log (written by the nightly script with the service key) ----------
create table if not exists public.jumpbag_reminders (
  id        bigint generated by default as identity primary key,
  when_at   timestamptz not null default now(),
  unit      text not null,
  item_id   bigint,
  exp_date  date,
  milestone text not null default ''       -- 30 | 7 | 0 | expired
);
revoke all on public.jumpbag_reminders from anon;
grant select on public.jumpbag_reminders to authenticated;
alter table public.jumpbag_reminders enable row level security;
drop policy if exists "admin read" on public.jumpbag_reminders;
create policy "admin read" on public.jumpbag_reminders for select to authenticated using (public.is_admin());

-- ---------- 4. the setting ----------
insert into public.settings (setting, value)
select 'Jump Bag Reminder Days', '30, 7, 0'
 where not exists (select 1 from public.settings where setting = 'Jump Bag Reminder Days');

-- ---------- 5. the tile ----------
insert into public.tiles (order_col, label, type, target, admin_only, icon, image, active)
select '18', 'My Jump Bag', 'jumpbag', '', '', 'bag', 'tile-icons/tile-jump-bag.png', 'X'
 where not exists (select 1 from public.tiles where lower(type) = 'jumpbag');

