  active     text default 'X'
);
revoke all on public.jumpbag_items from anon;
grant select, insert, update, delete on public.jumpbag_items to authenticated;
grant usage, select on all sequences in schema public to authenticated;
alter table public.jumpbag_items enable row level security;
drop policy if exists "member read" on public.jumpbag_items;
create policy "member read" on public.jumpbag_items for select to authenticated using (public.is_member());
drop policy if exists "admin write" on public.jumpbag_items;
create policy "admin write" on public.jumpbag_items for all to authenticated using (public.is_admin()) with check (public.is_admin());

