-- ============================================================
--  CALL STATISTICS  (app 1.16.0, Nov 2026)
--
--  How many calls each responder ran per quarter, split by crew role
--  (Lead / Driver / Other). Today the numbers are imported from ESO
--  (Admin -> Call stats -> Import: paste the ESO export, or the pull
--  Claude does from the ESO Insights dashboard). Later the Hatzalah Web
--  feed will write the same rows (source = 'web').
--
--  The member's My Standing screen reads their own rows; admins read all.
--  call_stats_names links the name ESO uses ("Yisroel Leibowitz",
--  "ELIMELECH (ELI) LITVINTCHOUK") to the roster unit; the import fills
--  unit from it, and the admin can fix unmatched names in the app.
--
--  Applied to the live project on Nov 22, 2026 through the Supabase
--  connector; kept here so a fresh database can be rebuilt.
-- ============================================================

create table if not exists public.call_stats (
  id          bigint generated by default as identity primary key,
  unit        text not null default '',        -- roster unit (blank until the name is linked)
  crew_name   text not null,                   -- the name exactly as the source spells it
  period      text not null,                   -- '2026-Q4'
  total       integer not null default 0,
  lead        integer not null default 0,
  driver      integer not null default 0,
  other       integer not null default 0,
  unknown     integer not null default 0,      -- role missing on the record
  source      text not null default 'eso',     -- eso | web | manual
  updated_at  timestamptz not null default now(),
  unique (crew_name, period, source)
);
create index if not exists idx_call_stats_unit_period on public.call_stats (unit, period);

create table if not exists public.call_stats_names (
  crew_name   text primary key,
  unit        text not null
);

alter table public.call_stats enable row level security;
alter table public.call_stats_names enable row level security;

drop policy if exists "own or admin read" on public.call_stats;
create policy "own or admin read" on public.call_stats for select to authenticated
  using (lower(trim(coalesce(unit,''))) = lower(trim(coalesce(my_unit(),'~none~'))) or is_admin());
drop policy if exists "admin write" on public.call_stats;
create policy "admin write" on public.call_stats for all to authenticated
  using (is_admin()) with check (is_admin());

drop policy if exists "admin all" on public.call_stats_names;
create policy "admin all" on public.call_stats_names for all to authenticated
  using (is_admin()) with check (is_admin());
