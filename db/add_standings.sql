-- ============================================================
--  STANDINGS at the end of a quarter  (app 1.21.0, Nov 2026)
--
--  Ships switched OFF. Every quarter the background job works out who fell
--  below their minimum and writes one row per responder here. While the
--  switches are off it only records what it WOULD have done ("would_notice",
--  "would_downgrade") — nothing is emailed and nobody's status changes. When
--  leadership approves, the Standings settings turn it on and the same job
--  starts acting on it.
--
--  streak = consecutive quarters below minimum, counted from the rows in this
--  table. Logging begins when this ships, so the clock starts fresh — nobody is
--  downgraded for quarters they were never warned about.
-- ============================================================

create table if not exists public.standings_log (
  id          bigint generated by default as identity primary key,
  unit        text not null,
  period      text not null,                 -- '2026-Q4'
  status      text not null default '',      -- their standing at the time
  need        integer not null default 0,    -- the minimum that applied
  total       integer not null default 0,    -- calls they ran
  short       boolean not null default false,
  streak      integer not null default 0,
  action      text not null default '',      -- would_notice | would_downgrade | notice | downgrade | excused | ok
  note        text not null default '',
  by_whom     text not null default '',      -- the admin, when a human did it
  created_at  timestamptz not null default now(),
  unique (unit, period)
);
create index if not exists idx_standings_log_period on public.standings_log (period);

revoke all on public.standings_log from anon;
grant select, insert, update, delete on public.standings_log to authenticated;
alter table public.standings_log enable row level security;

drop policy if exists "own or admin read" on public.standings_log;
create policy "own or admin read" on public.standings_log for select to authenticated
  using (lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin());
drop policy if exists "admin write" on public.standings_log;
create policy "admin write" on public.standings_log for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- the switches, all off to begin with (settings has no unique key on "setting",
-- so each row is added only when it is not already there)
insert into public.settings (setting, value)
select v.setting, v.value
from (values ('Standings Notices','Off'),
             ('Standings Auto Downgrade','Off'),
             ('Standings Quarters Before Downgrade','2')) as v(setting, value)
where not exists (
  select 1 from public.settings s where lower(trim(s.setting)) = lower(trim(v.setting))
);
