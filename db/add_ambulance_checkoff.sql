-- ============================================================
--  AMBULANCE CHECKOFF  (app 1.4.0)
--
--  1) a "Service unit" switch on each member (and "Service Unit" as a Type)
--  2) the table the checkoffs are saved in
--  3) the list of ambulances (a setting you can edit later)
--  4) the home-screen tile - shown only to service units and admins
--
--  Run once in Supabase: SQL Editor -> New query -> paste -> Run.
-- ============================================================

-- ---------- 1. the role ----------
alter table public.roster add column if not exists service_unit text default '';

-- "Service Unit" as a member Type (added to the comma list if it is not there yet)
update public.settings
   set value = trim(both ', ' from value) || ', Service Unit'
 where setting = 'Member Types'
   and lower(coalesce(value,'')) not like '%service unit%';
insert into public.settings (setting, value)
select 'Member Types', 'Responder, Non Responder, Dispatcher, Service Unit'
 where not exists (select 1 from public.settings where setting = 'Member Types');

-- ---------- 2. the checkoffs ----------
create table if not exists public.ambulance_checks (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  unit        text not null,              -- who did it (H-24, Service 1 ...)
  name        text not null default '',
  ambulance   text not null,              -- A1 Ambulance - 1
  log_type    text not null,              -- weekly | monthly | maintenance
  check_date  date not null,
  answers     jsonb not null default '{}'::jsonb,   -- every question's answer, by key
  photos      jsonb not null default '[]'::jsonb,   -- [{key, ref, name}] - files in the private docs bucket
  flags       jsonb not null default '[]'::jsonb,   -- things worth an admin's look (low tire, damage, ...)
  notes       text not null default '',
  app_version text not null default ''
);

create index if not exists idx_ambulance_checks_date on public.ambulance_checks (check_date desc, created_at desc);
create index if not exists idx_ambulance_checks_amb  on public.ambulance_checks (ambulance, log_type, check_date desc);

revoke all on public.ambulance_checks from anon;
grant select, insert, update, delete on public.ambulance_checks to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.ambulance_checks enable row level security;

-- Any member can read (so the app can show "last checked on ..."); a member adds their own; admins can fix or remove.
drop policy if exists "member read"  on public.ambulance_checks;
create policy "member read"  on public.ambulance_checks
  for select to authenticated using (public.is_member());

drop policy if exists "own insert"   on public.ambulance_checks;
create policy "own insert"   on public.ambulance_checks
  for insert to authenticated
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() );

drop policy if exists "admin update" on public.ambulance_checks;
create policy "admin update" on public.ambulance_checks
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admin delete" on public.ambulance_checks;
create policy "admin delete" on public.ambulance_checks
  for delete to authenticated using (public.is_admin());

-- ---------- 3. the ambulances ----------
insert into public.settings (setting, value)
select 'Ambulances', 'A1 Ambulance - 1, A2 Ambulance - 2'
 where not exists (select 1 from public.settings where setting = 'Ambulances');

-- ---------- 4. the tile ----------
insert into public.tiles (order_col, label, type, target, admin_only, icon, image, active)
select '17', 'Ambulance Checkoff', 'ambcheck', '', '', 'clipboard', 'tile-icons/tile-ambulance-checkoff.png', 'X'
 where not exists (select 1 from public.tiles where lower(type) = 'ambcheck');

-- ---------- check it worked ----------
select setting, value from public.settings where setting in ('Member Types','Ambulances');
select label, type, image from public.tiles where lower(type) = 'ambcheck';
select count(*) as checks_so_far from public.ambulance_checks;
