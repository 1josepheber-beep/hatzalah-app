-- ============================================================
--  MY JUMP BAG - bag check date + "remind me" (app 1.5.1)
--
--  One row per member: when they last went through their whole bag
--  ("I checked my bag today"), how often they want to be reminded to do
--  it (0 = off), and when the nightly script last reminded them.
--
--  Run once in Supabase: SQL Editor -> New query -> paste -> Run.
--  (Safe to run again - nothing is dropped.)
-- ============================================================

create table if not exists public.jumpbag_bags (
  id           bigint generated by default as identity primary key,
  unit         text not null unique,
  checked_at   timestamptz,                    -- last "I checked my bag today"
  remind_days  integer not null default 0,     -- 0 = no reminder; 30 / 60 / 90 / 180
  reminded_at  timestamptz                     -- last "time to check your bag" reminder sent
);
revoke all on public.jumpbag_bags from anon;
grant select, insert, update, delete on public.jumpbag_bags to authenticated;
grant usage, select on all sequences in schema public to authenticated;
alter table public.jumpbag_bags enable row level security;

drop policy if exists "own or admin read" on public.jumpbag_bags;
create policy "own or admin read" on public.jumpbag_bags for select to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() );
drop policy if exists "own insert" on public.jumpbag_bags;
create policy "own insert" on public.jumpbag_bags for insert to authenticated
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) );
drop policy if exists "own update" on public.jumpbag_bags;
create policy "own update" on public.jumpbag_bags for update to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) )
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) );
drop policy if exists "own or admin delete" on public.jumpbag_bags;
create policy "own or admin delete" on public.jumpbag_bags for delete to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() );

-- ---------- check it worked ----------
select count(*) as bags_on_file from public.jumpbag_bags;
