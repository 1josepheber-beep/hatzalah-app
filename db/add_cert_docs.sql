-- ============================================================
--  CERTIFICATION DOCUMENTS
--
--  One row per document a member uploads when renewing a
--  certification. The file itself lives in the private "docs"
--  bucket under certs/<unit>/...; this table is the index the
--  admin portal reads ("View document" / "No document on file").
--
--  The app writes the new expiration date ONLY after the file has
--  been stored and this row has been recorded, so a date can no
--  longer be saved without its document from the member's side.
--  Admins can still type a date by hand in the admin portal.
--
--  Run once in Supabase: SQL Editor -> New query -> paste -> Run.
-- ============================================================

create table if not exists public.cert_docs (
  id            bigint generated by default as identity primary key,
  unit          text not null,
  certification text not null,          -- the certification's display name, e.g. "American Heart BLS"
  path          text not null,          -- storage path inside the docs bucket
  expires       text,                   -- the expiration date saved with it, M/D/YYYY
  file_name     text,                   -- the file's original name, for the admin's benefit
  size_bytes    bigint,
  uploaded_by   text,                   -- unit of whoever did the upload (a member, or an admin on their behalf)
  uploaded_at   timestamptz not null default now()
);

create index if not exists idx_cert_docs_unit on public.cert_docs (unit);

-- the anonymous key never sees this; signed-in members do, within the rules below
revoke all on public.cert_docs from anon;
grant select, insert, delete on public.cert_docs to authenticated;
grant usage, select on all sequences in schema public to authenticated;

alter table public.cert_docs enable row level security;

-- Members see their own documents; admins see everyone's.
drop policy if exists "own or admin read" on public.cert_docs;
create policy "own or admin read" on public.cert_docs
  for select to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() );

-- Members may record a document for themselves; admins for anyone.
drop policy if exists "own or admin insert" on public.cert_docs;
create policy "own or admin insert" on public.cert_docs
  for insert to authenticated
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() );

-- Only admins can remove a record.
drop policy if exists "admin delete" on public.cert_docs;
create policy "admin delete" on public.cert_docs
  for delete to authenticated using (public.is_admin());

-- Check: should return the table with 0 rows and no error.
select count(*) as documents_on_file from public.cert_docs;
