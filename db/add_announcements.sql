-- ============================================================
--  ANNOUNCEMENTS, CONFIRMATIONS AND POLLS
--
--  Three kinds of notice, one table:
--    feature  - "we added a thing". Shows once, no record kept.
--    confirm  - stays on the home screen until the member ticks
--               and confirms. Who confirmed and when is recorded.
--    poll     - one vote each, changeable until it closes.
--
--  Run this once in the Supabase SQL editor.
-- ============================================================

create table if not exists public.announcements (
  id           bigint generated by default as identity primary key,
  order_col    text,
  kind         text default 'feature',    -- feature | confirm | poll
  title        text,
  body         text,
  target       text,                      -- tile type to jump to, e.g. 'certifications'
  audience     text default 'everyone',   -- everyone | admins
  options      text,                      -- poll choices, one per line
  show_results text default 'X',          -- polls: do members see the running count
  anonymous    text default '',           -- polls: X = never record who voted
  show_until   text,                      -- M/D/YYYY, blank = no end date
  active       text default 'X'
);

alter table public.announcements enable row level security;

drop policy if exists "member read" on public.announcements;
create policy "member read" on public.announcements
  for select to authenticated using (public.is_member());

drop policy if exists "admin write" on public.announcements;
create policy "admin write" on public.announcements
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());


-- ---------- who has seen / confirmed / voted ----------
create table if not exists public.announcement_reads (
  id       bigint generated by default as identity primary key,
  ann_id   bigint not null,
  unit     text not null,
  action   text,                          -- seen | confirmed | voted
  choice   text,                          -- the poll option they picked
  at       timestamptz default now()
);

create unique index if not exists uq_announcement_reads
  on public.announcement_reads (ann_id, unit);
create index if not exists idx_announcement_reads_ann
  on public.announcement_reads (ann_id);

alter table public.announcement_reads enable row level security;

-- Members may read the records (needed to show poll totals and to know what
-- they have already dealt with) and may write only their own row.
drop policy if exists "member read reads" on public.announcement_reads;
create policy "member read reads" on public.announcement_reads
  for select to authenticated using (public.is_member());

drop policy if exists "member write own" on public.announcement_reads;
create policy "member write own" on public.announcement_reads
  for insert to authenticated with check (public.is_member());

drop policy if exists "member update own" on public.announcement_reads;
create policy "member update own" on public.announcement_reads
  for update to authenticated using (public.is_member()) with check (public.is_member());

drop policy if exists "admin manage reads" on public.announcement_reads;
create policy "admin manage reads" on public.announcement_reads
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());


-- ---------- record a response ----------
-- One row per member per announcement. Voting again replaces the choice.
-- An anonymous poll records the vote with no unit attached, so it can never
-- be traced back later.
create or replace function public.announcement_respond(
  p_ann_id bigint, p_unit text, p_action text, p_choice text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare anon boolean; k text;
begin
  if not public.is_member() then
    return json_build_object('ok', false, 'error', 'Not a member');
  end if;
  if coalesce(trim(p_unit),'') = '' then
    return json_build_object('ok', false, 'error', 'No unit');
  end if;

  select coalesce(anonymous,'') = 'X', coalesce(kind,'feature')
    into anon, k
    from public.announcements where id = p_ann_id;

  if k is null then
    return json_build_object('ok', false, 'error', 'Not found');
  end if;

  if anon and k = 'poll' then
    -- no unit stored at all, so there is nothing to trace
    insert into public.announcement_reads (ann_id, unit, action, choice)
    values (p_ann_id, '-', 'voted', p_choice);
  else
    insert into public.announcement_reads (ann_id, unit, action, choice, at)
    values (p_ann_id, trim(p_unit), p_action, p_choice, now())
    on conflict (ann_id, unit) do update
      set action = excluded.action,
          choice = excluded.choice,
          at     = now();
  end if;

  return json_build_object('ok', true);
end;
$$;

revoke all on function public.announcement_respond(bigint, text, text, text) from public;
grant execute on function public.announcement_respond(bigint, text, text, text) to authenticated;


