-- ============================================================
--  RESTOCK REQUESTS  (app 1.6.0)
--
--  "Request restock" in My Jump Bag and "Order needed" in the ambulance
--  inventory checklist both write one row here. The Apps Script emails
--  and pushes every active admin and service unit; admins and service
--  units mark a request Ordered / Done in the app.
--
--  Run once in Supabase: SQL Editor -> New query -> paste -> Run.
-- ============================================================

-- who handles supplies: admins and anyone with the Service unit switch
create or replace function public.is_service_unit()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.roster r
    where lower(trim(r.email)) = lower(trim(coalesce(auth.jwt() ->> 'email','')))
      and ( lower(trim(coalesce(r.service_unit,''))) in ('x','yes','true')
            or lower(trim(coalesce(r.type,''))) like '%service unit%' )
      and lower(trim(coalesce(r.active,''))) not in ('no','off','false','0')
  );
$$;

create table if not exists public.supply_requests (
  id          bigint generated by default as identity primary key,
  created_at  timestamptz not null default now(),
  unit        text not null,                         -- who asked
  name        text not null default '',
  source      text not null default 'jumpbag',       -- jumpbag | inventory
  ambulance   text not null default '',              -- for inventory requests
  items       jsonb not null default '[]'::jsonb,    -- [{item_id, name, qty, why}]
  note        text not null default '',
  status      text not null default 'open',          -- open | ordered | done
  status_by   text not null default '',
  status_at   timestamptz,
  notified    text not null default ''               -- what the script sent, for the record
);
create index if not exists idx_supply_requests_status on public.supply_requests (status, created_at desc);
create index if not exists idx_supply_requests_unit   on public.supply_requests (unit, created_at desc);

revoke all on public.supply_requests from anon;
grant select, insert, update, delete on public.supply_requests to authenticated;
grant usage, select on all sequences in schema public to authenticated;
alter table public.supply_requests enable row level security;

-- a member sees their own requests; admins and service units see them all
drop policy if exists "own or handlers read" on public.supply_requests;
create policy "own or handlers read" on public.supply_requests for select to authenticated
  using ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) or public.is_admin() or public.is_service_unit() );
drop policy if exists "own insert" on public.supply_requests;
create policy "own insert" on public.supply_requests for insert to authenticated
  with check ( lower(trim(coalesce(unit,''))) = lower(trim(coalesce(public.my_unit(),'~none~'))) );
drop policy if exists "handlers update" on public.supply_requests;
create policy "handlers update" on public.supply_requests for update to authenticated
  using ( public.is_admin() or public.is_service_unit() ) with check ( public.is_admin() or public.is_service_unit() );
drop policy if exists "admin delete" on public.supply_requests;
create policy "admin delete" on public.supply_requests for delete to authenticated
  using ( public.is_admin() );

-- ---------- check it worked ----------
select count(*) as requests_on_file from public.supply_requests;
