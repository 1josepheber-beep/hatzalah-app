-- ============================================================
--  RESOURCES  —  SOPs, rules, forms and other documents that
--  members can read in the app.
--
--  Files live in a PRIVATE bucket called "docs". Unlike the
--  existing "image" bucket, nothing in here can be opened by a
--  plain link. The app asks Supabase for a short-lived signed
--  link each time a member taps a document, and that link stops
--  working after one hour.
--
--  Run this whole file once in the Supabase SQL editor.
-- ============================================================

-- ---------- 1. the private bucket ----------
insert into storage.buckets (id, name, public, file_size_limit)
values ('docs', 'docs', false, 52428800)          -- 50 MB per file
on conflict (id) do update
  set public = false,
      file_size_limit = 52428800;

-- Only signed-in people may touch it. There is deliberately no
-- "public" policy here — that is what makes it private.
drop policy if exists "docs read"   on storage.objects;
create policy "docs read"   on storage.objects
  for select to authenticated using (bucket_id = 'docs');

drop policy if exists "docs write"  on storage.objects;
create policy "docs write"  on storage.objects
  for insert to authenticated with check (bucket_id = 'docs');

drop policy if exists "docs update" on storage.objects;
create policy "docs update" on storage.objects
  for update to authenticated using (bucket_id = 'docs');

drop policy if exists "docs delete" on storage.objects;
create policy "docs delete" on storage.objects
  for delete to authenticated using (bucket_id = 'docs');

-- ---------- 2. the table ----------
create table if not exists public.resources (
  id          bigint generated by default as identity primary key,
  order_col   text,
  title       text,
  description text,
  file        text,
  active      text default 'X'
);

alter table public.resources enable row level security;

-- Members read, admins write — same rule the rest of your tables use.
drop policy if exists "member read" on public.resources;
create policy "member read" on public.resources
  for select to authenticated using (public.is_member());

drop policy if exists "admin write" on public.resources;
create policy "admin write" on public.resources
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- ---------- 3. the tile ----------
-- Adds a Resources tile to the home screen. Delete this block if
-- you would rather add the tile yourself in Admin -> Tiles.
insert into public.tiles (order_col, label, type, target, admin_only, icon, image, active)
select '16', 'Resources', 'resources', '', '', 'clipboard', '', 'X'
where not exists (select 1 from public.tiles where lower(type) = 'resources');

-- ---------- 4. check it worked ----------
select id, name, public from storage.buckets where id = 'docs';   -- public must be false
select count(*) as resource_rows from public.resources;
select label, type from public.tiles where lower(type) = 'resources';
